/**
 * Vercel Serverless Function: AI Academic Advisor Proxy
 *
 * Supports server-side environment variables (OPENROUTER_API_KEY, GEMINI_API_KEY, GROQ_API_KEY)
 * or client-supplied keys, protecting keys from browser exposure and enabling 0-setup deployment.
 */

export default async function handler(req, res) {
  // CORS Headers
  res.setHeader('Access-Control-Allow-Credentials', 'true');
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'GET,OPTIONS,POST');
  res.setHeader(
    'Access-Control-Allow-Headers',
    'X-CSRF-Token, X-Requested-With, Accept, Accept-Version, Content-Length, Content-MD5, Content-Type, Date, X-Api-Version'
  );

  if (req.method === 'OPTIONS') {
    return res.status(200).end();
  }

  if (req.method === 'GET') {
    // Health / Environment check endpoint
    return res.status(200).json({
      status: 'ok',
      runtime: 'vercel-serverless',
      configuredKeys: {
        openrouter: Boolean(process.env.OPENROUTER_API_KEY),
        gemini: Boolean(process.env.GEMINI_API_KEY),
        groq: Boolean(process.env.GROQ_API_KEY),
      },
    });
  }

  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Method Not Allowed' });
  }

  const {
    provider = 'openrouter',
    apiKey = '',
    model = '',
    prompt = '',
    systemInstructions = '',
    conversationHistory = [],
    augmentedPrompt = '',
  } = req.body || {};

  const cleanPrompt = (prompt || augmentedPrompt || '').trim();
  if (!cleanPrompt) {
    return res.status(400).json({ error: 'Prompt is required' });
  }

  const startTime = Date.now();

  try {
    // 1. OPENROUTER
    if (provider === 'openrouter') {
      const key = (apiKey?.trim() || process.env.OPENROUTER_API_KEY || '').trim();
      if (!key) {
        return res.status(401).json({
          error: 'No OpenRouter API key found. Set OPENROUTER_API_KEY in Vercel settings or enter key in app.',
        });
      }

      const chosenModel = model || 'deepseek/deepseek-r1:free';
      const messages = [
        {
          role: 'system',
          content: [
            {
              type: 'text',
              text: systemInstructions || 'You are the official UIU AI Academic Advisor.',
              cache_control: { type: 'ephemeral' },
            },
          ],
        },
        ...conversationHistory.slice(-4).map((m) => ({
          role: m.role === 'user' ? 'user' : 'assistant',
          content: m.text,
        })),
        {
          role: 'user',
          content: cleanPrompt,
        },
      ];

      const apiRes = await fetch('https://openrouter.ai/api/v1/chat/completions', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${key}`,
          'HTTP-Referer': 'https://ez-uiu.vercel.app',
          'X-Title': 'EZ_UIU Vercel Advisor',
        },
        body: JSON.stringify({
          model: chosenModel,
          messages,
          temperature: 0.35,
          max_tokens: 850,
        }),
      });

      if (!apiRes.ok) {
        const errJson = await apiRes.json().catch(() => ({}));
        return res.status(apiRes.status).json({
          error: errJson?.error?.message || `OpenRouter API error (HTTP ${apiRes.status})`,
        });
      }

      const data = await apiRes.json();
      const reply = data?.choices?.[0]?.message?.content;
      if (!reply) throw new Error('No text generated by OpenRouter');

      const cachedTokens =
        data.usage?.prompt_tokens_details?.cached_tokens ||
        data.usage?.cache_read_input_tokens ||
        0;

      return res.status(200).json({
        text: reply,
        usage: {
          promptTokens: data.usage?.prompt_tokens || 0,
          completionTokens: data.usage?.completion_tokens || 0,
          cachedTokens,
        },
        latencyMs: Date.now() - startTime,
        isServerless: true,
        source: 'vercel-openrouter',
      });
    }

    // 2. GOOGLE GEMINI
    if (provider === 'gemini') {
      const key = (apiKey?.trim() || process.env.GEMINI_API_KEY || '').trim();
      if (!key) {
        return res.status(401).json({
          error: 'No Gemini API key found. Set GEMINI_API_KEY in Vercel settings or enter key in app.',
        });
      }

      const chosenModel = model || 'gemini-1.5-flash';
      const url = `https://generativelanguage.googleapis.com/v1beta/models/${chosenModel}:generateContent?key=${key}`;

      const apiRes = await fetch(url, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          contents: [
            {
              role: 'user',
              parts: [{ text: `${systemInstructions}\n\n${cleanPrompt}` }],
            },
          ],
          generationConfig: {
            temperature: 0.35,
            maxOutputTokens: 850,
          },
        }),
      });

      if (!apiRes.ok) {
        const errJson = await apiRes.json().catch(() => ({}));
        return res.status(apiRes.status).json({
          error: errJson?.error?.message || `Gemini API error (HTTP ${apiRes.status})`,
        });
      }

      const data = await apiRes.json();
      const reply = data?.candidates?.[0]?.content?.parts?.[0]?.text;
      if (!reply) throw new Error('No text generated by Gemini');

      return res.status(200).json({
        text: reply,
        latencyMs: Date.now() - startTime,
        isServerless: true,
        source: 'vercel-gemini',
      });
    }

    // 3. GROQ
    if (provider === 'groq') {
      const key = (apiKey?.trim() || process.env.GROQ_API_KEY || '').trim();
      if (!key) {
        return res.status(401).json({
          error: 'No Groq API key found. Set GROQ_API_KEY in Vercel settings or enter key in app.',
        });
      }

      const chosenModel = model || 'llama-3.3-70b-versatile';
      const apiRes = await fetch('https://api.groq.com/openai/v1/chat/completions', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${key}`,
        },
        body: JSON.stringify({
          model: chosenModel,
          messages: [
            { role: 'system', content: systemInstructions },
            ...conversationHistory.slice(-4).map((m) => ({
              role: m.role === 'user' ? 'user' : 'assistant',
              content: m.text,
            })),
            { role: 'user', content: cleanPrompt },
          ],
          temperature: 0.35,
          max_tokens: 850,
        }),
      });

      if (!apiRes.ok) {
        const errJson = await apiRes.json().catch(() => ({}));
        return res.status(apiRes.status).json({
          error: errJson?.error?.message || `Groq API error (HTTP ${apiRes.status})`,
        });
      }

      const data = await apiRes.json();
      const reply = data?.choices?.[0]?.message?.content;
      if (!reply) throw new Error('No text generated by Groq');

      return res.status(200).json({
        text: reply,
        latencyMs: Date.now() - startTime,
        isServerless: true,
        source: 'vercel-groq',
      });
    }

    return res.status(400).json({ error: `Unsupported provider: ${provider}` });
  } catch (err) {
    return res.status(500).json({
      error: err.message || 'Internal server error processing AI query',
    });
  }
}
