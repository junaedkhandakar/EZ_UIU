/**
 * Vercel Serverless Function: OpenRouter AI Academic Advisor Proxy
 *
 * Exclusively proxies requests to OpenRouter with server-side OPENROUTER_API_KEY support,
 * prompt caching optimization, and student context injection.
 */

export default async function handler(req, res) {
  res.setHeader('Access-Control-Allow-Credentials', 'true');
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'GET,OPTIONS,POST');
  res.setHeader(
    'Access-Control-Allow-Headers',
    'X-CSRF-Token, X-Requested-With, Accept, Accept-Version, Content-Length, Content-MD5, Content-Type, Date, X-Api-Version'
  );

  if (req.method === 'OPTIONS') {
    return res.status(200).end();
  }

  // Health / Environment check endpoint
  if (req.method === 'GET') {
    return res.status(200).json({
      status: 'ok',
      runtime: 'vercel-serverless',
      provider: 'openrouter',
      hasOpenRouterKey: Boolean(process.env.OPENROUTER_API_KEY),
    });
  }

  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Method Not Allowed' });
  }

  const {
    apiKey = '',
    model = 'deepseek/deepseek-r1:free',
    prompt = '',
    systemInstructions = '',
    conversationHistory = [],
    augmentedPrompt = '',
  } = req.body || {};

  const cleanPrompt = (prompt || augmentedPrompt || '').trim();
  if (!cleanPrompt) {
    return res.status(400).json({ error: 'Prompt is required' });
  }

  const effectiveKey = (apiKey?.trim() || process.env.OPENROUTER_API_KEY || '').trim();
  if (!effectiveKey) {
    return res.status(401).json({
      error: 'No OpenRouter API key found. Set OPENROUTER_API_KEY in Vercel project settings or enter key in app.',
    });
  }

  const startTime = Date.now();

  try {
    const chosenModel = model || 'deepseek/deepseek-r1:free';
    const messages = [
      {
        role: 'system',
        content: [
          {
            type: 'text',
            text: systemInstructions || 'You are the official UIU AI Academic Advisor.',
            cache_control: { type: 'ephemeral' },
          },
        ],
      },
      ...conversationHistory.slice(-4).map((m) => ({
        role: m.role === 'user' ? 'user' : 'assistant',
        content: m.text,
      })),
      {
        role: 'user',
        content: cleanPrompt,
      },
    ];

    const apiRes = await fetch('https://openrouter.ai/api/v1/chat/completions', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${effectiveKey}`,
        'HTTP-Referer': 'https://ez-uiu.vercel.app',
        'X-Title': 'EZ_UIU OpenRouter Advisor',
      },
      body: JSON.stringify({
        model: chosenModel,
        messages,
        temperature: 0.35,
        max_tokens: 850,
      }),
    });

    if (!apiRes.ok) {
      const errJson = await apiRes.json().catch(() => ({}));
      return res.status(apiRes.status).json({
        error: errJson?.error?.message || `OpenRouter API error (HTTP ${apiRes.status})`,
      });
    }

    const data = await apiRes.json();
    const reply = data?.choices?.[0]?.message?.content;
    if (!reply) throw new Error('No text generated by OpenRouter');

    const cachedTokens =
      data.usage?.prompt_tokens_details?.cached_tokens ||
      data.usage?.cache_read_input_tokens ||
      0;

    return res.status(200).json({
      text: reply,
      usage: {
        promptTokens: data.usage?.prompt_tokens || 0,
        completionTokens: data.usage?.completion_tokens || 0,
        cachedTokens,
      },
      latencyMs: Date.now() - startTime,
      isServerless: true,
      model: chosenModel,
    });
  } catch (err) {
    return res.status(500).json({
      error: err.message || 'Internal server error communicating with OpenRouter',
    });
  }
}
